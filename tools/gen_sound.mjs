// Turns the original mod's armor_breaking.ogg (MIT, uku3lig/armor-hud) into
// mixins/ukus_armor_hud/sound/src/ogg.rs: a .hnmod only carries .rs/.toml.
// Deterministic: same input bytes, same output file.
// Usage: node tools/gen_sound.mjs <path to armor_breaking.ogg>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node tools/gen_sound.mjs <armor_breaking.ogg>");
  process.exit(1);
}
const bytes = readFileSync(src);
const rows = [];
for (let i = 0; i < bytes.length; i += 24) {
  rows.push("    " + Array.from(bytes.subarray(i, i + 24), (b) => `0x${b.toString(16).padStart(2, "0")},`).join(" "));
}
const out =
  "// Generated by tools/gen_sound.mjs from assets/ukus-armor-hud/sounds/armor_breaking.ogg\n" +
  "// of uku3lig/armor-hud (MIT, Copyright (c) 2021 BerdinskiyBear). Do not edit.\n" +
  `pub static OGG: [u8; ${bytes.length}] = [\n${rows.join("\n")}\n];\n`;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
writeFileSync(join(root, "mixins/ukus_armor_hud/sound/src/ogg.rs"), out.replace(/\r\n/g, "\n"));
console.log(`ogg.rs: ${bytes.length} bytes`);
